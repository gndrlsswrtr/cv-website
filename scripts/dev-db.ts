import fs from "node:fs";
import path from "node:path";

import EmbeddedPostgres from "embedded-postgres";

import { applyMigrations } from "@/lib/db/migrate";
import { closePool } from "@/lib/db/pool";
import { loadEnv } from "./lib/load-env";

/**
 * A persistent local PostgreSQL for development.
 *
 *   npm run db:dev          # start it, migrate, write .env.local — then leave it running
 *   npm run db:dev -- --reset   # throw the data away and start clean
 *
 * No Docker and no local PostgreSQL install: the binaries ship with the
 * `embedded-postgres` devDependency, the same instance the test suite uses.
 * The data lives in `.data/postgres`, which is gitignored, so it survives
 * reboots but not a deliberate `--reset`.
 *
 * This is a development convenience. Production uses Railway's PostgreSQL —
 * see README → "Deploying to Railway".
 */

const PORT = Number(process.env.DEV_DB_PORT ?? 54329);
const DATA_DIR = path.join(process.cwd(), ".data", "postgres");
const USER = "postgres";
const PASSWORD = "postgres";
const DATABASE = "portfolio";

const URL = `postgresql://${USER}:${PASSWORD}@127.0.0.1:${PORT}/${DATABASE}`;

const ENV_FILE = path.join(process.cwd(), ".env.local");

/** Writes DATABASE_URL without clobbering any other setting the user has. */
function writeEnvLocal(): void {
  const existing = fs.existsSync(ENV_FILE) ? fs.readFileSync(ENV_FILE, "utf8") : "";
  const withoutDatabaseUrl = existing
    .split(/\r?\n/)
    .filter((line) => !line.trim().startsWith("DATABASE_URL"))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd();

  const header = `# Generated by \`npm run db:dev\` — local development database.\n# Delete this file to stop pointing the app at it.\n`;

  const next = `${header}\nDATABASE_URL=${URL}\n${
    withoutDatabaseUrl ? `\n${withoutDatabaseUrl}\n` : ""
  }`;
  fs.writeFileSync(ENV_FILE, next, "utf8");
}

async function main(): Promise<void> {
  loadEnv();

  const reset = process.argv.includes("--reset");
  if (reset) {
    fs.rmSync(DATA_DIR, { recursive: true, force: true });
    console.log(`Removed ${DATA_DIR}`);
  }

  const firstRun = !fs.existsSync(path.join(DATA_DIR, "PG_VERSION"));
  fs.mkdirSync(DATA_DIR, { recursive: true });

  const server = new EmbeddedPostgres({
    databaseDir: DATA_DIR,
    user: USER,
    password: PASSWORD,
    port: PORT,
    persistent: true,
    onLog: () => undefined,
    onError: (message) => process.stderr.write(`${String(message).trimEnd()}\n`),
  });

  if (firstRun) {
    console.log("Initialising a new PostgreSQL data directory (first run only)...");
    await server.initialise();
  }

  console.log(`Starting PostgreSQL on port ${PORT}...`);
  await server.start();

  if (firstRun || reset) {
    await server.createDatabase(DATABASE);
    console.log(`Created database "${DATABASE}".`);
  }

  // Point the app at it *before* opening a pool, then apply migrations through
  // the same code path the app uses.
  process.env.DATABASE_URL = URL;
  console.log("Applying migrations...");
  const applied = await applyMigrations();
  console.log(
    applied.length === 0
      ? "Database is already up to date."
      : `Applied ${applied.length}: ${applied.join(", ")}`,
  );

  await closePool();
  writeEnvLocal();

  console.log(`\nReady. DATABASE_URL written to .env.local:\n  ${URL}`);
  console.log("\nNext steps (in another terminal):");
  console.log("  npm run db:create-admin    # create the first admin account");
  console.log("  npm run dev                # then open http://localhost:3000");
  console.log("\nLeave this process running. Press Ctrl+C to stop the database.\n");

  const stop = async () => {
    console.log("\nStopping PostgreSQL...");
    await server.stop().catch(() => undefined);
    process.exit(0);
  };
  process.on("SIGINT", stop);
  process.on("SIGTERM", stop);

  // Keep the process alive until interrupted.
  await new Promise(() => undefined);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
